"""Diagnostics for the mapping-table translator.

Produces the numbers needed for the coverage documentation:

* which rule rows fired on the supplied OC document and which never fired,
  grouped by the supplier's ``spine`` label;
* which OC leaves had no covering rule, grouped by path prefix;
* the emitted SONiC tables with counts.

Usage::

    python tools/diagnose.py --oc data/raw/oc/<file>.json --out docs/coverage.md
"""

from __future__ import annotations

import argparse
import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from translator.cli import DEFAULT_OC, DEFAULT_RULES  # noqa: E402
from translator.engine import Translator  # noqa: E402
from translator.ocdoc import OcDocument  # noqa: E402
from translator.rules import load_rules  # noqa: E402


def build_report(oc_path: Path, rules_path: Path) -> dict:
    rules = load_rules(str(rules_path))
    document = OcDocument.load(str(oc_path))
    translator = Translator(rules, document)
    config = translator.translate()
    report = translator.report

    fired = report.rule_fires
    by_spine: dict[str, dict[str, int]] = collections.defaultdict(
        lambda: {"rules": 0, "fired": 0, "emissions": 0}
    )
    for rule in rules:
        entry = by_spine[rule.spine]
        entry["rules"] += 1
        if rule.index in fired:
            entry["fired"] += 1
            entry["emissions"] += sum(
                1 for emission in report.emissions if emission.rule_index == rule.index
            )

    unmatched = collections.Counter()
    for path in report.unmatched_leaves:
        segments = path.split("//")
        unmatched["//".join(segments[:3])] += 1

    return {
        "summary": report.summary(),
        "spines": dict(sorted(by_spine.items())),
        "unmatched_prefixes": dict(sorted(unmatched.items())),
        "tables": {table: len(keys) for table, keys in config.items()},
        "warnings": report.warnings,
    }


def to_markdown(report: dict, oc_name: str) -> str:
    summary = report["summary"]
    lines = [
        f"# Coverage report for `{oc_name}`",
        "",
        "Generated by `python tools/diagnose.py`.",
        "",
        "## Totals",
        "",
        "| metric | value |",
        "| --- | --- |",
    ]
    for key, value in summary.items():
        if isinstance(value, dict):
            continue
        lines.append(f"| {key} | {value} |")
    lines += ["", "## Emitted SONiC tables", "", "| table | keys |", "| --- | --- |"]
    for table, count in report["tables"].items():
        lines.append(f"| {table} | {count} |")
    lines += [
        "",
        "## Rule rows per supplier group",
        "",
        "`rules` = rows in the CSV for that group, `fired` = rows that matched at",
        "least one OC path in this document, `emissions` = fields written.",
        "",
        "| spine | rules | fired | emissions |",
        "| --- | --- | --- | --- |",
    ]
    for spine, entry in report["spines"].items():
        lines.append(
            f"| {spine} | {entry['rules']} | {entry['fired']} | {entry['emissions']} |"
        )
    lines += [
        "",
        "## OC leaves without a covering rule (top prefixes)",
        "",
        "| path prefix | leaves |",
        "| --- | --- |",
    ]
    ranked = sorted(report["unmatched_prefixes"].items(), key=lambda item: -item[1])
    for prefix, count in ranked[:80]:
        lines.append(f"| `{prefix}` | {count} |")
    if report["warnings"]:
        lines += ["", "## Translation warnings", "", "```"]
        lines += report["warnings"]
        lines += ["```", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--oc", default=str(DEFAULT_OC))
    parser.add_argument("--rules", default=str(DEFAULT_RULES))
    parser.add_argument("--out", default=str(ROOT / "docs" / "coverage.md"))
    parser.add_argument("--json-out", default="")
    args = parser.parse_args(argv)

    report = build_report(Path(args.oc), Path(args.rules))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(to_markdown(report, Path(args.oc).name), encoding="utf-8")
    if args.json_out:
        Path(args.json_out).write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
